import { spawn, exec } from 'child_process';
import { promisify } from 'util';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { PlaylistItem, PlaylistResponse } from './types.js';

const execAsync = promisify(exec);

export interface YtAuthStatus {
  enabled: boolean;
  source: 'env' | 'ui' | 'none';
  hasCookies: boolean;
  hasPoToken: boolean;
  updatedAt: number | null;
}

export class YtDlpService {
  private binaryCmd: string = 'yt-dlp';
  private isDirectBinary: boolean = true;
  private cookiesFilePath: string = path.join(os.tmpdir(), 'ytb-circuitbend-cookies.txt');
  private hasActiveCookies: boolean = false;
  private authSource: 'env' | 'ui' | 'none' = 'none';
  private poToken: string = '';
  private visitorData: string = '';
  private updatedAt: number | null = null;

  constructor() {
    this.detectExecutable();
    this.initFromEnv();
  }

  /**
   * Automatically load optional YouTube / Google credentials from environment variables if configured on Render
   */
  private initFromEnv() {
    const envCookies = process.env.YOUTUBE_COOKIES || process.env.YT_COOKIES;
    const envPoToken = process.env.YOUTUBE_PO_TOKEN || '';
    const envVisitorData = process.env.YOUTUBE_VISITOR_DATA || '';

    if (envPoToken) {
      this.poToken = envPoToken.trim();
    }
    if (envVisitorData) {
      this.visitorData = envVisitorData.trim();
    }

    if (envCookies && envCookies.trim().length > 0) {
      try {
        let decoded = envCookies.trim();
        // Support Base64-encoded cookies.txt in env var
        if (!decoded.includes('\t') && !decoded.includes('=') && /^[A-Za-z0-9+/=]+$/.test(decoded)) {
          decoded = Buffer.from(decoded, 'base64').toString('utf-8');
        }
        this.writeCookiesFile(decoded, 'env');
        console.log('[yt-dlp] Loaded optional YouTube cookies from environment variable.');
      } catch (err) {
        console.warn('[yt-dlp] Failed to load YOUTUBE_COOKIES from env:', err);
      }
    }
  }

  /**
   * Converts either a standard Netscape cookies.txt string OR a raw HTTP Cookie header
   * (e.g. "SID=...; __Secure-1PSID=...; LOGIN_INFO=...") into a valid Netscape cookies.txt file.
   */
  private normalizeToNetscapeCookies(input: string): string {
    const trimmed = input.trim();
    if (trimmed.startsWith('# Netscape HTTP Cookie File') || trimmed.includes('\tTRUE\t') || trimmed.includes('\tFALSE\t')) {
      return trimmed.startsWith('# Netscape')
        ? trimmed
        : `# Netscape HTTP Cookie File\n# https://curl.haxx.se/rfc/cookie_spec.html\n\n${trimmed}\n`;
    }

    // Parse raw "key=value; key2=value2" Cookie header into Netscape format for .youtube.com & .google.com
    const lines: string[] = [
      '# Netscape HTTP Cookie File',
      '# https://curl.haxx.se/rfc/cookie_spec.html',
      '# Generated by CIRCUIT//BEND Studio',
      ''
    ];
    const expiry = Math.floor(Date.now() / 1000) + 86400 * 365;
    const pairs = trimmed
      .replace(/^Cookie:\s*/i, '')
      .split(/[;\r\n]+/)
      .map((s) => s.trim())
      .filter(Boolean);

    for (const pair of pairs) {
      const eqIdx = pair.indexOf('=');
      if (eqIdx <= 0) continue;
      const name = pair.slice(0, eqIdx).trim();
      const val = pair.slice(eqIdx + 1).trim();
      if (!name || !val) continue;
      const secure = name.startsWith('__Secure') || name.startsWith('__Host') || name.includes('SAPISID') ? 'TRUE' : 'FALSE';
      lines.push(`.youtube.com\tTRUE\t/\t${secure}\t${expiry}\t${name}\t${val}`);
    }

    return lines.join('\n') + '\n';
  }

  public writeCookiesFile(rawCookiesInput: string, source: 'env' | 'ui' = 'ui') {
    const normalized = this.normalizeToNetscapeCookies(rawCookiesInput);
    fs.writeFileSync(this.cookiesFilePath, normalized, 'utf-8');
    this.hasActiveCookies = true;
    this.authSource = source;
    this.updatedAt = Date.now();
  }

  public setCredentials(options: { cookies?: string; poToken?: string; visitorData?: string }) {
    if (typeof options.poToken === 'string') {
      this.poToken = options.poToken.trim();
    }
    if (typeof options.visitorData === 'string') {
      this.visitorData = options.visitorData.trim();
    }
    if (options.cookies && options.cookies.trim().length > 0) {
      this.writeCookiesFile(options.cookies, 'ui');
    } else if (this.poToken) {
      this.authSource = 'ui';
      this.updatedAt = Date.now();
    }
  }

  public clearCredentials() {
    this.hasActiveCookies = false;
    this.poToken = '';
    this.visitorData = '';
    this.authSource = 'none';
    this.updatedAt = null;
    try {
      if (fs.existsSync(this.cookiesFilePath)) {
        fs.unlinkSync(this.cookiesFilePath);
      }
    } catch {}
  }

  public getAuthStatus(): YtAuthStatus {
    const fileExists = this.hasActiveCookies && fs.existsSync(this.cookiesFilePath);
    return {
      enabled: fileExists || Boolean(this.poToken),
      source: fileExists || this.poToken ? this.authSource : 'none',
      hasCookies: fileExists,
      hasPoToken: Boolean(this.poToken),
      updatedAt: this.updatedAt
    };
  }

  /**
   * Builds yt-dlp extractor and authentication arguments.
   * - If optional Google/YouTube cookies are provided, passes `--cookies <file>` and uses web/tv/android clients.
   * - If no cookies are provided, uses `tv_embedded,ios,mweb,android` clients which avoid most cloud bot blocks.
   */
  public getAuthAndExtractorArgs(): string[] {
    const args: string[] = [];
    const hasCookies = this.hasActiveCookies && fs.existsSync(this.cookiesFilePath);

    if (hasCookies) {
      args.push('--cookies', this.cookiesFilePath);
    }

    let extractorArg = hasCookies
      ? 'youtube:player_client=web,tv_embedded,mweb,ios'
      : 'youtube:player_client=tv_embedded,ios,mweb,android';

    if (this.poToken) {
      extractorArg += `;po_token=web+${this.poToken}`;
    }
    if (this.visitorData) {
      extractorArg += `;visitor_data=${this.visitorData}`;
    }

    args.push('--extractor-args', extractorArg);
    return args;
  }

  public async detectExecutable() {
    // 1. Direct yt-dlp binary (standard in Linux / Render PATH)
    try {
      await execAsync('yt-dlp --version');
      this.binaryCmd = 'yt-dlp';
      this.isDirectBinary = true;
      return;
    } catch {}

    // 2. Python 3 module (Linux / Ubuntu standard)
    try {
      await execAsync('python3 -m yt_dlp --version');
      this.binaryCmd = 'python3';
      this.isDirectBinary = false;
      return;
    } catch {}

    // 3. Python standard
    try {
      await execAsync('python -m yt_dlp --version');
      this.binaryCmd = 'python';
      this.isDirectBinary = false;
      return;
    } catch {}

    // 4. Windows py launcher
    this.binaryCmd = 'py';
    this.isDirectBinary = false;
  }

  public async getExecutable(): Promise<string> {
    await this.detectExecutable();
    return this.isDirectBinary ? this.binaryCmd : `${this.binaryCmd} -m yt_dlp`;
  }

  /**
   * Parse a YouTube playlist or single video URL and return metadata
   */
  public async parseUrl(url: string, _baseUrl: string): Promise<PlaylistResponse> {
    await this.detectExecutable();

    return new Promise((resolve, reject) => {
      const baseArgs = [
        '--flat-playlist',
        '-J',
        '--no-warnings',
        '--no-check-certificates',
        '--js-runtimes',
        'node',
        ...this.getAuthAndExtractorArgs(),
        url
      ];

      const args = this.isDirectBinary ? baseArgs : ['-m', 'yt_dlp', ...baseArgs];

      console.log(`[yt-dlp] Fetching metadata for ${url} (auth=${this.hasActiveCookies ? 'cookies' : 'anonymous'})...`);

      const child = spawn(this.binaryCmd, args, { shell: false });
      let stdout = '';
      let stderr = '';

      child.stdout.on('data', (chunk) => {
        stdout += chunk.toString();
      });

      child.stderr.on('data', (chunk) => {
        stderr += chunk.toString();
      });

      child.on('close', (code) => {
        if (code !== 0 && !stdout) {
          console.error('[yt-dlp] Error output:', stderr);
          return reject(new Error(`yt-dlp exited with code ${code}: ${stderr || 'Unknown error'}`));
        }

        try {
          const jsonStartIndex = stdout.indexOf('{');
          if (jsonStartIndex === -1) {
            throw new Error(`No JSON output from yt-dlp. ExitCode: ${code}. Stderr: ${stderr.trim() || 'none'}`);
          }
          const jsonStr = stdout.slice(jsonStartIndex);
          const data = JSON.parse(jsonStr);

          const items: PlaylistItem[] = [];
          const playlistTitle = data.title || (data._type === 'playlist' ? 'YouTube Playlist' : 'YouTube Video');

          if (data.entries && Array.isArray(data.entries)) {
            for (const entry of data.entries) {
              if (!entry || (!entry.id && !entry.url)) continue;
              const videoId = entry.id || (entry.url ? entry.url.replace(/^.*(?:youtu.be\/|v\/|e\/|u\/\w+\/|embed\/|v=)([^#&?]*).*/, '$1') : '');

              let thumbnail = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
              if (entry.thumbnails && entry.thumbnails.length > 0) {
                thumbnail = entry.thumbnails[entry.thumbnails.length - 1].url;
              } else if (entry.thumbnail) {
                thumbnail = entry.thumbnail;
              }

              items.push({
                id: videoId,
                title: entry.title || 'Untitled Track',
                duration: entry.duration || 0,
                thumbnail,
                streamUrl: `/api/stream?id=${videoId}`,
                author: entry.uploader || entry.channel || entry.artist || ''
              });
            }
          } else {
            const videoId = data.id || 'video';
            let thumbnail = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
            if (data.thumbnails && data.thumbnails.length > 0) {
              thumbnail = data.thumbnails[data.thumbnails.length - 1].url;
            } else if (data.thumbnail) {
              thumbnail = data.thumbnail;
            }

            items.push({
              id: videoId,
              title: data.title || 'Untitled Track',
              duration: data.duration || 0,
              thumbnail,
              streamUrl: `/api/stream?id=${videoId}`,
              author: data.uploader || data.channel || data.artist || ''
            });
          }

          resolve({
            playlistTitle,
            items
          });
        } catch (err: any) {
          reject(new Error(`Failed to parse yt-dlp output: ${err.message}`));
        }
      });

      child.on('error', (err) => {
        reject(err);
      });
    });
  }

  /**
   * Spawns a yt-dlp process to stream video & audio muxed directly into stdout
   */
  public createStreamProcess(idOrUrl: string) {
    const targetUrl = idOrUrl.startsWith('http')
      ? idOrUrl
      : `https://www.youtube.com/watch?v=${idOrUrl}`;

    const baseArgs = [
      '-f',
      '18/b[height<=720]/best[height<=720]/best',
      '--no-playlist',
      '--no-warnings',
      '--no-part',
      '--no-check-certificates',
      '--js-runtimes',
      'node',
      ...this.getAuthAndExtractorArgs(),
      '--retries',
      '10',
      '--fragment-retries',
      '10',
      '--socket-timeout',
      '30',
      '-o',
      '-',
      targetUrl
    ];

    const args = this.isDirectBinary ? baseArgs : ['-m', 'yt_dlp', ...baseArgs];

    console.log(`[yt-dlp] Spawning stream for ${targetUrl} (auth=${this.hasActiveCookies ? 'cookies' : 'anonymous'})`);
    return spawn(this.binaryCmd, args, { shell: false });
  }
}
